local function ResolveVIPWelcomeMessage(language, profile)
    if not profile or not profile.nameKey then
        return nil
    end

    local messageKey = VIP_NAME_ALIASES[profile.nameKey]
    if profile.firstNameKey then
        messageKey = VIP_NAME_ALIASES[profile.firstNameKey] or VIP_NAME_ALIASES[profile.surnameKey]
    end
    if not messageKey then
        return nil
    end

    local languageMessages = VIP_WELCOME_MESSAGES[language] or VIP_WELCOME_MESSAGES.EN
    return languageMessages[messageKey] or VIP_WELCOME_MESSAGES.EN[messageKey]
end

local function AppendNameMessages(messages, language, profile)
    if not profile or not profile.nameKey then
        return
    end

    local source = NAME_WELCOME_MESSAGES[language]
    if not source then
        return
    end

    if profile.nameKey:match("^nya") and source.nya_prefix then
        for index = 1, #source.nya_prefix do
            messages[#messages + 1] = source.nya_prefix[index]
        end
        return
    end

    local matchedMessageKeys = {}

    for fragment, fragmentMessages in pairs(source) do
        if fragment ~= "nya_prefix" and fragment ~= "ussy_suffix"
            and string.find(profile.nameKey, fragment, 1, true) then
            for index = 1, #fragmentMessages do
                messages[#messages + 1] = fragmentMessages[index]
            end
            matchedMessageKeys[fragment] = true
        end
    end

    for fragment, messageKey in pairs(NAME_FRAGMENT_ALIASES) do
        local fragmentMessages = source[messageKey]
        if not source[fragment] and not matchedMessageKeys[messageKey] and fragmentMessages
            and string.find(profile.nameKey, fragment, 1, true) then
            for index = 1, #fragmentMessages do
                messages[#messages + 1] = fragmentMessages[index]
            end
            matchedMessageKeys[messageKey] = true
        end
    end

    if profile.nameKey:match("ussy$") and source.ussy_suffix then
        for index = 1, #source.ussy_suffix do
            messages[#messages + 1] = source.ussy_suffix[index]
        end
    end
end

local function ResolveGeneratedWelcomeMessages(language)
    local resolvedLanguage = GENERATED_WELCOME_PARTS[language] and language or "EN"
    local parts = GENERATED_WELCOME_PARTS[resolvedLanguage]
    local messages = {}

    for _, starter in ipairs(parts.starters or {}) do
        for _, ending in ipairs(parts.endings or {}) do
            local text
            if ending == "" then
                text = starter
            else
                text = starter .. " " .. ending
            end

            table.insert(messages, {
                text = text,
                source = "generated",
                cooldownKey = "generated-ending:" .. ending,
            })
        end
    end

    return messages
end

